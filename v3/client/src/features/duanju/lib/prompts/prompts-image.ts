/**
 * 短剧生图 prompt 模板（共识 D6-D7 / 资料第 3-4 课）
 *
 * - characterSheetPrompt：角色设定图（三视图式正面全身·无复杂动作·外观锚点全量注入）
 * - sceneImagePrompt：场景图（无人物·空间结构/光影基调/关键道具）
 * - 画风前缀统一注入（project.style）
 */

/** 画风 → 生图风格描述（比自由文本更可控；自定义画风原样透传） */
const STYLE_PROMPTS: Record<string, string> = {
  动漫风: '日系动漫插画风格，赛璐璐上色，线条干净，色彩明亮通透',
  '3D 卡通': '3D 卡通渲染风格，皮克斯质感，造型圆润，材质柔和',
  写实: '写实风格，照片级真实感，自然光影，质感与细节纤毫毕现',
  国漫: '国产动漫风格，唯美古韵与现代结合，色彩饱和，笔触细腻',
  水墨: '水墨画风，留白意境，笔锋浓淡相宜，宣纸质感',
};

export function stylePrefix(style: string): string {
  return STYLE_PROMPTS[style] ?? `${style}风格`;
}

/**
 * 角色设定图 prompt（2026-11-12 版式定稿：用户拍板「直接生成三视图」）——
 * 横版单次生成：仅并排三张全身像（正面/侧面/背面），无特写无其他区块。
 * 双段合成（左特写+右三视图）已回退——合成缩放导致右区过度压缩，用户实测否决。
 * 竖版画幅会触发模型 2×2 重复铺排先验，必须配横版尺寸（comfy 1344×768 / 云端 3:2）。
 */
export function characterSheetPrompt(style: string, name: string, profile: string): string {
  return [
    `${stylePrefix(style)}，角色三视图 reference sheet（仅三张全身像，无特写、无其他区块）`,
    `【角色：${name}】${profile}`,
    '版式要求：画面仅并排三张全身像——正面全身、侧面全身、背面全身；站立姿态自然挺直，双臂自然下垂，双脚与肩同宽；三张等距分布、大小一致、撑满画面高度。',
    '渲染要求：边缘清晰锐利，材质与纹理细节真实可辨（毛发纤毫毕现/布料垂坠感/纹样与配饰做工），影棚级柔光均匀照明，无强烈投影。',
    '一致性要求：三张画面五官/发型/体型/服装/配饰完全一致，同一人物同一画风；浅灰色干净背景，留白分隔，无文字标签',
  ].join('\n');
}

/**
 * 设定图双段 prompt（版式硬规定 v2·零压缩）：左头像特写 448×768 + 右三视图 1344×768
 * 各自高遵循任务 → App 内 canvas 合成 1792×768（两段原尺寸落位，无压缩）。
 */
export function characterSheetSplitPrompts(
  style: string,
  name: string,
  profile: string,
): { portrait: string; triView: string } {
  return {
    portrait: [
      `${stylePrefix(style)}，单人角色头像特写`,
      `【角色：${name}】${profile}`,
      '画面要求：肩部以上大特写，正面微侧，五官清晰锐利，眼神有神，表情自然；人物居中占满画面。',
      '渲染要求：影棚级柔光均匀照明，无强烈投影，边缘清晰，服装领口与发型细节真实可辨；浅灰色干净背景，无文字',
    ].join('\n'),
    triView: [
      `${stylePrefix(style)}，角色三视图 reference sheet（仅三张全身像，无特写、无其他区块）`,
      `【角色：${name}】${profile}`,
      '版式要求：画面仅并排三张全身像——正面全身、侧面全身、背面全身；站立姿态自然挺直，双臂自然下垂，双脚与肩同宽；三张等距分布、大小一致、撑满画面高度。',
      '渲染要求：边缘清晰锐利，材质与纹理细节真实可辨（毛发纤毫毕现/布料垂坠感/纹样与配饰做工），影棚级柔光均匀照明，无强烈投影。',
      '一致性要求：三张画面五官/发型/体型/服装/配饰完全一致，同一人物同一画风；浅灰色干净背景，留白分隔，无文字标签',
    ].join('\n'),
  };
}

/** 场景图 prompt（详细版）：构图三层纵深 + 光影交互 + 时间温度氛围，画面氛围统一不乱跳 */
export function sceneImagePrompt(style: string, name: string, spec: string): string {
  return [
    `${stylePrefix(style)}，电影级场景概念图（无人物）`,
    `【场景：${name}】${spec}`,
    '构图要求：广角视野交代完整空间，透视自然，画面分前/中/远三层纵深——前景细节锚定视觉、中景展开空间主体、远景收束氛围。',
    '光影要求：明确主光源方向与色温倾向，材质反光与环境光交互真实（湿润表面反光、金属高光、布料吸光），明暗对比服务空间层次。',
    '氛围要求：把场景的时间感与温度感画出来（雨夜湿冷、清晨薄雾、黄昏暖尘等），关键道具清晰可辨、位置合理。',
    '纯净要求：无任何人物与动物出现，无文字水印，画质细腻，作为后续分镜的场景参考基准',
  ].join('\n');
}
